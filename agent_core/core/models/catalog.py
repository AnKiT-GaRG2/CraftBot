# -*- coding: utf-8 -*-
"""What a model can take, and what its provider does, read from the vendored
model catalog.

model_catalog.json (next to this module, so it ships with the code and an
upgrade replaces it) is generated by scripts/gen_model_catalog.py from the
sources and facts in scripts/model_catalog_sources.json. Nothing is fetched
at runtime, and no model or provider fact lives in code: what the catalog
does not list gets the defaults below.

Model rows are keyed ``<surface>/<model_id>`` with the surface from
``reasoning_surface``, the same keys as the reasoning table, and match the
EXACT model id (no prefix or substring matching).

Defaults for what the catalog does not list:

* a model: no row (None); callers use settings.json model.context_window
  and show no cache countdown;
* a surface: its responses report cached input.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from enum import Enum
from functools import lru_cache
from pathlib import Path
from typing import Any, Mapping, Optional

from agent_core.core.models.reasoning import reasoning_surface

CATALOG_PATH = Path(__file__).with_name("model_catalog.json")


class CacheLifetimeKind(str, Enum):
    #: The provider keeps the cache at least this long after a request.
    EXACT = "exact"
    #: The provider's usual figure only; it may drop the cache sooner.
    TYPICAL = "typical"


@dataclass(frozen=True)
class CacheLifetime:
    """How long a request's prompt cache stays usable after it starts."""

    kind: CacheLifetimeKind
    seconds: int


@dataclass(frozen=True)
class ModelLimits:
    """What the catalog says about one model."""

    #: Input plus output tokens the model accepts.
    context_window: int
    #: Input tokens the provider accepts whatever output is requested, when
    #: it caps input below the window.
    max_input_tokens: Optional[int] = None
    #: How long the provider keeps the model's prompt cache; None when the
    #: provider documents no lifetime.
    cache_lifetime: Optional[CacheLifetime] = None


@lru_cache(maxsize=1)
def _catalog() -> Mapping[str, Any]:
    with open(CATALOG_PATH, encoding="utf-8") as f:
        return json.load(f)


def model_limits(
    provider: Optional[str], model: Optional[str], auth_mode: str = "api_key"
) -> Optional[ModelLimits]:
    """The catalogued facts of ``model`` on ``provider``, or None."""
    if not provider or not model:
        return None
    row = _catalog()["models"].get(f"{reasoning_surface(provider, auth_mode)}/{model}")
    if row is None:
        return None
    lifetime = row.get("cache_lifetime")
    return ModelLimits(
        context_window=row["context_window"],
        max_input_tokens=row.get("max_input_tokens"),
        cache_lifetime=(
            CacheLifetime(CacheLifetimeKind(lifetime["kind"]), lifetime["seconds"])
            if lifetime
            else None
        ),
    )


def reports_cached_tokens(provider: Optional[str], auth_mode: str = "api_key") -> bool:
    """Whether ``provider``'s responses say how much input came from cache."""
    if not provider:
        return True
    facts = _catalog()["surfaces"].get(reasoning_surface(provider, auth_mode), {})
    return facts.get("reports_cached_tokens", True)
