# -*- coding: utf-8 -*-
"""Context limits per model, read from the vendored model catalog.

model_catalog.json (next to this module, so it ships with the code and an
upgrade replaces it) is generated by scripts/gen_model_catalog.py from
models.dev, the Codex model catalogue (ChatGPT-subscription surface) and
scripts/catalog_overrides.json. Nothing is fetched at runtime.

Rows are keyed ``<surface>/<model_id>`` with the surface from
``reasoning_surface``, the same keys as the reasoning table, and match the
EXACT model id (no prefix or substring matching). A model with no row is not
catalogued; its caller uses settings.json model.context_window.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Mapping, Optional

from agent_core.core.models.reasoning import reasoning_surface

CATALOG_PATH = Path(__file__).with_name("model_catalog.json")


@dataclass(frozen=True)
class ModelLimits:
    """What a model can take in one request."""

    #: Input plus output tokens the model accepts.
    context_window: int
    #: Input tokens the provider accepts whatever output is requested, when
    #: it caps input below the window (GPT-5: 272,000 of a 400,000 window).
    max_input_tokens: Optional[int] = None


@lru_cache(maxsize=1)
def _rows() -> Mapping[str, Mapping[str, int]]:
    with open(CATALOG_PATH, encoding="utf-8") as f:
        return json.load(f)["models"]


def model_limits(
    provider: Optional[str], model: Optional[str], auth_mode: str = "api_key"
) -> Optional[ModelLimits]:
    """The catalogued limits of ``model`` on ``provider``, or None."""
    if not provider or not model:
        return None
    row = _rows().get(f"{reasoning_surface(provider, auth_mode)}/{model}")
    if row is None:
        return None
    return ModelLimits(
        context_window=row["context_window"],
        max_input_tokens=row.get("max_input_tokens"),
    )
